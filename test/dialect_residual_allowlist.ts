// Allowlist for the test in test/dialect_residual.test.ts. That test raises
// ordinary request bodies, response bodies, and stream events, and splits
// every op that is not a core op into units. The comment "A unit" in that
// file gives the rules for a unit string.
//
// providerOnly: units whose data only one provider has. A row is here only
// when the public API references of the other providers were read and none
// has the data; the reason names each reference. All units of one piece of
// data sit in the same list.
//
// baseline: the residuals that main has today. A row is the unit string
// only, and makes no claim about other providers. Each row is backlog: a
// later pull request raises its data to a core op, or moves the row to
// providerOnly with a reason. A later pull request removes rows from
// baseline and adds none, with one exception: a new corpus case for an input
// that main already raises adds the rows that the case produces.
//
// A change under src that leaves a new unit in a raised program must either
// raise the data to a core op or add a providerOnly row with a reason. A row
// in either list that the corpus no longer produces fails the test and must
// be removed, so every row stays checked.

